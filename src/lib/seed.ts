const PROFILE_FACTOR: Record<Profile, [number, number]> = {
  strong: [1.0, 1.08],
  onTrack: [0.93, 1.02],
  atRisk: [0.8, 0.9],
  lagging: [0.6, 0.76],
};

function buildKpis(): Kpi[] {
  const rand = rng(77123);
  const quarters: Array<{ year: number; q: 1 | 2 | 3 | 4 }> = [];
  for (let y = STRATEGY_START; y <= CURRENT_YEAR; y++) {
    for (let q = 1 as 1 | 2 | 3 | 4; q <= 4; q++) {
      if (y === CURRENT_YEAR && q > CURRENT_QUARTER) break;
      quarters.push({ year: y, q: q as 1 | 2 | 3 | 4 });
    }
  }
  const totalSpan = (STRATEGY_END - STRATEGY_START + 1) * 4;

  return KPI_SPECS.map((s, i) => {
    const id = `k${i + 1}`;
    const [code, name, objectiveId, initiativeId, perspectiveId, unit, direction, baseline, target, weight, profile, desc] = s;
    const [lo, hi] = PROFILE_FACTOR[profile];
    const init = initiativeId ? INITIATIVES.find((x) => x.id === initiativeId) : undefined;

    const readings: KpiReading[] = quarters.map((qq, idx) => {
      const step = (idx + 1) / totalSpan;
      const qTarget = baseline + (target - baseline) * step;
      const factor = lo + rand() * (hi - lo);
      // في اتجاه التخفيض، الأداء الجيد يعني قيمة فعلية أقل من المستهدف
      const raw =
        direction === "increase"
          ? baseline + (qTarget - baseline) * factor
          : baseline - (baseline - qTarget) * factor;
      const dec = unit === "index" ? 1 : unit === "number" ? 0 : 1;
      const isLast = idx === quarters.length - 1;
      return {
        id: `${id}-r${idx + 1}`,
        kpiId: id,
        year: qq.year,
        quarter: qq.q,
        target: Number(qTarget.toFixed(dec)),
        // الربع الحالي مفتوح للإدخال في بعض المؤشرات لإظهار حالة "بانتظار القراءة"
        actual: isLast && i % 6 === 0 ? null : Number(raw.toFixed(dec)),
        comment:
          isLast && i % 6 === 0
            ? ""
            : idx % 3 === 0
              ? "قراءة معتمدة من مصدر البيانات التشغيلي بعد مطابقة السجلات الربعية."
              : factor < 0.85
                ? "انحراف عن المستهدف نتيجة تأخر تسليم أحد المشاريع المرتبطة؛ خطة تصحيحية قيد التنفيذ."
                : "القراءة ضمن النطاق المستهدف وفق المتابعة الربعية المعتمدة.",
        byUserId: init?.ownerId ?? "u2",
        at: `${qq.year}-${String(qq.q * 3).padStart(2, "0")}-28T10:00:00.000Z`,
      };
    });

    return {
      id,
      code,
      name,
      description: desc,
      objectiveId,
      initiativeId,
      perspectiveId,
      unit,
      direction,
      baseline,
      target,
      weight,
      frequency: "quarterly" as const,
      ownerId: init?.ownerId ?? "u2",
      thresholdGreen: 95,
      thresholdAmber: 80,
      readings,
    };
  });
}

